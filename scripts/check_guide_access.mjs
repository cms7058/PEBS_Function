import assert from 'node:assert/strict';
import {DEFAULT_ACCESS,normalizeAccess,matchingAccess,visibleRecommendations,visibleSources,sourcePresentation} from '../src/guide-access.js';
const researcher={tier:'high',role:'admin',show_book_names:true};
const source={id:'L1',kind:'book',title:'PRIVATE BOOK NAME',page:123,url:'/reader.html?book=private&page=123'};
const legacy={sources:[source],recommendations:[{tier:'ultra',skill_id:'advanced'}]};
// Previously saved titles and page links cannot appear before fresh role verification.
assert.equal(sourcePresentation(source,legacy,DEFAULT_ACCESS).title,'');
assert.equal(sourcePresentation(source,legacy,DEFAULT_ACCESS).url,'');
assert.equal(sourcePresentation(source,legacy,DEFAULT_ACCESS).page,null);
assert(!sourcePresentation(source,legacy,DEFAULT_ACCESS).knowledge.includes('PRIVATE'));
assert.deepEqual(visibleRecommendations(legacy,researcher),[]);
assert.equal(sourcePresentation(source,legacy,researcher).title,'');
assert.deepEqual(normalizeAccess({tier:'owner',role:'owner',show_book_names:true}),DEFAULT_ACCESS);
assert.equal(normalizeAccess({tier:'ultra',role:'user',show_book_names:true}).show_book_names,false);
const current={access:researcher,sources:[source,{id:'S1',kind:'skill',tier:'ultra',knowledge_point:'Ultra method'}],recommendations:[{tier:'normal'},{tier:'high'},{tier:'ultra'},{tier:'unknown'}]};
assert(matchingAccess(current,researcher));
assert.deepEqual(visibleRecommendations(current,researcher).map(v=>v.tier),['normal','high']);
assert.equal(sourcePresentation(source,current,researcher).title,'PRIVATE BOOK NAME');
assert.equal(sourcePresentation(source,current,researcher).page,123);
assert.equal(sourcePresentation(source,current,researcher).url,source.url);
assert.equal(sourcePresentation({...source,kind:'skill',title:'Regression method',book_title:'PRIVATE BOOK NAME'},current,researcher).title,'PRIVATE BOOK NAME');
assert.equal(sourcePresentation({...source,kind:'skill',book_title:'PRIVATE BOOK NAME'},current,DEFAULT_ACCESS).title,'');
assert.equal(sourcePresentation(source,{...current,access_stale:true},researcher).title,'');
assert.deepEqual(visibleRecommendations({...current,access_stale:true},researcher),[]);
assert.deepEqual(visibleRecommendations(current,DEFAULT_ACCESS),[]);
assert.equal(visibleSources(current,DEFAULT_ACCESS).length,1);
assert.equal(sourcePresentation({...source,url:'javascript:alert(1)'},current,researcher).url,'');
assert.equal(sourcePresentation({...source,knowledge_point:'回归残差诊断'},legacy,DEFAULT_ACCESS).knowledge,'回归残差诊断');
console.log('PASS: legacy source title/page/link privacy, role downgrade, stale recommendations, tier limits, and safe source links');
